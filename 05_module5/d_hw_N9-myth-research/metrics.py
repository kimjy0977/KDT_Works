# ⛔버린 지표 — 「설명이 한 줄로 안 된다」
#   · 보고서 «가독성 점수»   판정 모델이 필요하다. 요건이 금지한 길이다
#   · 절 사이 «문체 일관성»  무엇이 좋은 건지 한 줄로 못 적었다
#   · 인용 «밀도 분산»       계산은 되는데 «어느 장치»를 보는지 말할 수 없었다
#   ★셋 다 «잴 수는 있었다». 못 적어서 버린 것이 아니라 «쓸 데를 몰라서» 버렸다.

def _거리(a, b):
    """편집거리 — 표준 라이브러리만 쓴다(레벤슈타인, O(len(a)*len(b)))."""
    prev = list(range(len(b) + 1))
    for x, ca in enumerate(a, 1):
        cur = [x]
        for y, cb in enumerate(b, 1):
            cur.append(min(prev[y] + 1, cur[y - 1] + 1,
                           prev[y - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def _가까운가(a, b):
    """이름 둘이 «한 글자만» 다른가 — 오타인가.

    ★비율(SequenceMatcher)을 먼저 써 봤다가 버렸다. 짧은 이름에 가혹하다 —
      「길가미시」vs「길가메시」가 0.75 라 ⛔정작 잡아야 할 것을 못 잡고,
      임계를 낮추면 「오시리스」vs「오시리스 신화」(0.73)까지 같다고 한다.
      둘은 코퍼스에 ★«따로» 있는 다른 문서다.
    ⇒ 편집거리 1 이하 + 길이차 1 이하. 설명이 한 줄로 끝난다.
    """
    return abs(len(a) - len(b)) <= 1 and _거리(a, b) <= 1


def 인용흔들림(인용, 읽음, 코퍼스제목=None):
    """★허위를 둘로 가른다 → (진짜허위, 표기흔들림[(쓴이름, 실제이름)])

    ★안전장치 — 인용한 이름이 «코퍼스에 실재하는 제목»이면 오타로 보지 않는다.
      실측으로 찾은 위험: 「이자나기」vs「이자나미」는 편집거리 1 인데
      ★한 글자 차이인 «다른 신»이다. 코퍼스에 둘 다 있으면 합쳐 버린다.
      ⇒ 실재하는 제목을 인용했으면 그건 «안 읽고 인용한» 것 — 진짜 허위다.
    """
    실재 = set(코퍼스제목 or [])
    진짜, 흔들림 = [], []
    for c in 인용:
        if c in 읽음:
            continue
        if c in 실재:          # ★코퍼스에 있는 «다른» 문서를 인용했다 → 진짜 허위
            진짜.append(c)
            continue
        비슷 = [d for d in 읽음 if _가까운가(c, d)]
        if 비슷:
            흔들림.append((c, 비슷[0]))
        else:
            진짜.append(c)
    return 진짜, 흔들림

def score(st):
    secs = 절모음(st.get("sections", []))
    from graph import DOCS   # ★함수 안 — graph 가 metrics 를 부르므로 순환을 피한다
    report = st.get("report") or ""

    # 근거율 — 문장 중 «문서명» 이 붙은 비율
    본문 = re.sub(r"^#.*$", "", report, flags=re.M)
    문장 = [x for x in re.split(r"(?<=[.!?。])\s+|\n+", 본문) if len(x.strip()) > 10]
    근거문장 = [x for x in 문장 if "«" in x]
    근거율 = len(근거문장) / max(1, len(문장))

    # 인용·읽음 집계
    인용 = [c for s in secs.values() for c in s["인용"]]
    읽음 = [d for s in secs.values() for d in s["읽음"]]
    # ★허위를 «둘로» 가른다 — 대응이 정반대라서다 (첫 실행에서 2건이 전부 오타였다)
    _진짜, _흔들림 = [], []
    for s in secs.values():
        a, b = 인용흔들림(s["인용"], s["읽음"], DOCS)
        _진짜 += a
        _흔들림 += b
    허위 = len(_진짜)
    흔들림 = _흔들림

    # 읽고 안 쓴 문서 — 예산을 쓰고 버린 것. 많으면 배정이 엉뚱했다는 뜻
    읽고안쓴 = sorted(set(읽음) - set(인용))

    # 최다 문서 편중 — 인용이 한 문서에 몰렸나
    c = collections.Counter(인용)
    편중 = (c.most_common(1)[0][1] / len(인용)) if 인용 else 0.0

    # 중복률 — 같은 문서를 두 절 이상이 읽은 비율
    읽은절수 = collections.Counter()
    for s in secs.values():
        for d in set(s["읽음"]):
            읽은절수[d] += 1
    겹친 = [d for d, n in 읽은절수.items() if n > 1]
    중복률 = len(겹친) / max(1, len(읽은절수))

    # ★꺾쇠 안 닫힘 — 보고서를 «읽다가» 찾았다. 지표는 못 잡던 것이다.
    #   «대홍수 신화$.  처럼 닫는 꺾쇠가 $ 로 나온다 (4절 중 3절에서).
    #   인용 정규식이 못 잡으므로 ★근거율이 «실제보다 낮게» 나온다.
    #   ⛔정규식을 느슨하게 풀지 않는다 — 다른 깨짐까지 삼킨다. 경보로 드러낸다.
    안닫힘 = report.count(chr(171)) - report.count(chr(187))

    # 인용 0곳인 절 — 자료 없이 쓴 절. 전체 근거율로는 안 보이는 구멍
    인용0 = [s["절"] for s in secs.values() if not s["인용"]]

    # ★격리율 — 코디네이터가 «본» 글자 ÷ 팀 전체가 «읽은» 글자
    #   한 자릿수 %여야 한다. 30%를 넘으면 격리가 무너지는 중이다.
    팀이읽은 = sum(len(DOCS.get(d, "")[:12000]) for d in 읽음)
    코디가본 = sum(len(s["원고"]) for s in secs.values())
    격리율 = 코디가본 / max(1, 팀이읽은)

    return {
        "근거율": round(근거율, 4),
        "문장수": len(문장),
        "허위인용": 허위,                      # ★경보 — 0이어야 한다 (진짜 환각만)
        "표기흔들림": len(흔들림),             # 읽은 문서를 «틀린 이름»으로 부른 것
        "표기흔들림_목록": 흔들림,            # (쓴 이름, 실제 이름)
        "읽고안쓴": 읽고안쓴,
        "편중": round(편중, 4),
        "중복률": round(중복률, 4),
        "꺾쇠안닫힘": max(0, 안닫힘),   # ★경보 — 0이어야 한다
        "인용0절": 인용0,
        "격리율": round(격리율, 4),
        # ★요건 — 「코디네이터가 본 글자 수와 서브에이전트가 본 글자 수를
        #   «따로» 셉니다」. 비율만 남기면 «무엇이 움직였나»를 못 본다 —
        #   격리율이 오르는 것은 원고가 길어진 것일 수도, 덜 읽은 것일 수도 있다.
        "코디가본글자": 코디가본,
        "팀이읽은글자": 팀이읽은,
        "읽은문서수": len(set(읽음)),
        "인용수": len(set(인용)),
        "보고서자수": len(report),
        "절수": len(secs),
        "바퀴": st.get("wheel", 0),
        "종료": st.get("종료", ""),
    }


def 절판정(sec, 코퍼스제목):
    """★절 하나를 «한 곳에서» 가른다 — 화면과 계기판이 같은 말을 하게.

    UI 를 만들다 드러난 것 — 절 카드는 「안 읽은 문서를 인용」이라 하고
    계기판은 같은 사건을 「표기 흔들림」이라 했다. ★한 화면에서 둘이 달랐다.
    원인은 graph.py 가 절을 만들 때 `not in 읽음` 으로 «그 자리에서» 판정하고,
    metrics.py 가 나중에 가른 것을 모르기 때문이다.

    ⇒ 판정은 여기 «한 곳»에만 둔다. graph.py 의 옛 필드는 남겨 둔다
      (runs.jsonl 에 이미 쌓인 기록과 호환을 깨지 않으려고).

    반환 — dict(진짜허위, 흔들림[(쓴이름,실제이름)], 실인용[표기 보정된 이름])
    """
    진짜, 흔들림 = 인용흔들림(sec["인용"], sec["읽음"], 코퍼스제목)
    고침 = dict(흔들림)
    실인용 = [고침.get(c, c) for c in sec["인용"] if c not in 진짜]
    return {"진짜허위": 진짜, "흔들림": 흔들림, "실인용": 실인용}
